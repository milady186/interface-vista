CREATE TABLE public.colaboradores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  cargo text NOT NULL,
  antiguedad_meses integer NOT NULL DEFAULT 1,
  campana text NOT NULL,
  turno text NOT NULL,
  sueldo numeric NOT NULL DEFAULT 1130,
  ausentismo numeric NOT NULL DEFAULT 0,
  tardanzas integer NOT NULL DEFAULT 0,
  quejas integer NOT NULL DEFAULT 0,
  penalidades integer NOT NULL DEFAULT 0,
  metas integer NOT NULL DEFAULT 100,
  satisfaccion numeric NOT NULL DEFAULT 7,
  horas_extra integer NOT NULL DEFAULT 100,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.colaboradores TO authenticated;
GRANT ALL ON public.colaboradores TO service_role;
ALTER TABLE public.colaboradores ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Personal ve colaboradores" ON public.colaboradores FOR SELECT TO authenticated USING (true);
CREATE POLICY "Personal crea colaboradores" ON public.colaboradores FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Personal edita colaboradores" ON public.colaboradores FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Personal elimina colaboradores" ON public.colaboradores FOR DELETE TO authenticated USING (true);

